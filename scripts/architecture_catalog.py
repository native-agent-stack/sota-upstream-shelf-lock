#!/usr/bin/env python3
"""Generate or verify zero-drift MADR 4.0 ADR catalog in docs/adr/CATALOG.md."""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ADR_DIR = pathlib.Path(__file__).resolve().parents[1] / "docs" / "adr"
CATALOG_PATH = ADR_DIR / "CATALOG.md"


def _extract_field(text: str, label: str) -> str:
    m = re.search(rf"^-\s+\*\*{re.escape(label)}:\*\*\s*(.+)$", text, flags=re.MULTILINE)
    return m.group(1).strip() if m else "UNKNOWN"


def render_catalog() -> tuple[str, int]:
    files = sorted(ADR_DIR.glob("ADR-*.md"))
    rows: list[str] = []
    for f in files:
        txt = f.read_text(encoding="utf-8")
        h1 = re.search(r"^#\s+(ADR-\d+):\s+(.+)$", txt, flags=re.MULTILINE)
        adr_id = h1.group(1) if h1 else f.stem[:8]
        title = h1.group(2).strip() if h1 else f.stem
        status = _extract_field(txt, "Status")
        date = _extract_field(txt, "Date")
        grade = _extract_field(txt, "Evidence Grade")
        rows.append(f"| [{adr_id}]({f.name}) | {title} | {status} | {date} | {grade} |")

    out = "\n".join(
        [
            "# SOTA Upstream Shelf Lock & Promotion Architecture Catalog",
            "",
            "<!-- GENERATED by scripts/architecture_catalog.py; do not edit by hand. -->",
            "",
            f"- **ADR Count:** {len(rows)} Accepted",
            "",
            "| ADR | Title | Status | Date | Grade |",
            "|---|---|---|---|---|",
            *rows,
            "",
        ]
    )
    return out, len(rows)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    expected, count = render_catalog()
    if args.check:
        if not CATALOG_PATH.is_file():
            print("ERROR: missing docs/adr/CATALOG.md", file=sys.stderr)
            return 1
        actual = CATALOG_PATH.read_text(encoding="utf-8")
        if actual != expected:
            print("ERROR: docs/adr/CATALOG.md drifted from ADR-*.md", file=sys.stderr)
            return 1
        print(f"PASS: {count} ADRs valid, 0 drift.")
        return 0

    CATALOG_PATH.write_text(expected, encoding="utf-8")
    print(f"WROTE {CATALOG_PATH} ({count} ADRs).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
